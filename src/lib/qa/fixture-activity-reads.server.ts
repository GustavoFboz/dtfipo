import { randomUUID } from 'node:crypto';
import { FixtureFailure, requireResult, type Check } from './fixture-acceptance.server';
import type { FixtureSession } from './fixture-sessions.server';

/** Only this claimed job's disposable case/activity is touched. Every receipt
 * and authorization check uses the actual USER session, never administration. */
export async function exerciseFixtureActivityReadPrivacy(
  fixture: FixtureSession, foreign: FixtureSession, jobId: string, caseId: string,
): Promise<Check[]> {
  const checks: Check[] = [];
  const activityId = randomUUID(), receiptId = randomUUID(), foreignReceiptId = randomUUID();
  const record = (check: string, passed: boolean) => {
    checks.push({ check, passed });
    if (!passed) throw new FixtureFailure(check.toUpperCase());
  };
  const selectOwn = async () => requireResult(await fixture.client.from('case_activity_reads')
    .select('id,activity_id,user_id,created_at').eq('id', receiptId).single(), 'FIXTURE_RECEIPT_READ_FAILED');
  try {
    const assurance = requireResult(await fixture.client.auth.mfa.getAuthenticatorAssuranceLevel(), 'FIXTURE_ASSURANCE_READ_FAILED');
    record('read_boundary_real_aal1_session', assurance.currentLevel === 'aal1');
    const dashboard = await fixture.client.rpc('platform_master_dashboard', { p_search: 'qa-fixture' });
    record('non_operator_master_dashboard_denied', dashboard.error?.message === 'PLATFORM_MASTER_FORBIDDEN');
    // Deliberately nonexistent Sandbox target. No real event is nominated, and
    // the expected refusal must be the operator guard before replay lookup.
    const replay = await fixture.client.rpc('platform_master_replay_asaas_event', {
      p_environment: 'sandbox', p_event_id: `qa-nonexistent-${jobId}`,
      p_reason: 'Disposable USER authorization boundary; no real payment target.',
    });
    record('non_operator_financial_replay_denied', replay.error?.message === 'PLATFORM_MASTER_FORBIDDEN');

    const activity = requireResult(await fixture.client.from('case_activity').insert({
      id: activityId, case_id: caseId, user_id: fixture.user_id,
      // The notification trigger ignores this dedicated kind. No messages,
      // mentions or stakeholder notifications are generated by this test.
      kind: 'qa_read_boundary', content: `DentalFlow disposable visibility ${jobId}`,
    }).select('id').single(), 'FIXTURE_ACTIVITY_CREATE_FAILED');
    record('owned_activity_real_insert', activity.id === activityId);
    const hiddenActivity = await foreign.client.from('case_activity').select('id').eq('id', activityId);
    record('foreign_activity_not_visible', !hiddenActivity.error && hiddenActivity.data?.length === 0);

    const receipt = requireResult(await fixture.client.from('case_activity_reads').insert({
      id: receiptId, activity_id: activityId, user_id: fixture.user_id,
    }).select('id,activity_id,user_id,created_at').single(), 'FIXTURE_RECEIPT_CREATE_FAILED');
    record('owned_receipt_real_insert', receipt.id === receiptId
      && receipt.activity_id === activityId && receipt.user_id === fixture.user_id);
    const repeated = requireResult(await fixture.client.from('case_activity_reads').upsert({
      activity_id: activityId, user_id: fixture.user_id, created_at: new Date().toISOString(),
    }, { onConflict: 'activity_id,user_id' }).select('id,activity_id,user_id,created_at').single(), 'FIXTURE_RECEIPT_UPSERT_FAILED');
    record('owned_receipt_upsert_idempotent', repeated.id === receiptId
      && repeated.activity_id === activityId && repeated.user_id === fixture.user_id);
    const preserved = (row: typeof repeated) => row.id === receiptId && row.activity_id === activityId
      && row.user_id === fixture.user_id && row.created_at === repeated.created_at;
    const hiddenReceipt = await foreign.client.from('case_activity_reads').select('id').eq('id', receiptId);
    record('foreign_receipt_not_visible', !hiddenReceipt.error && hiddenReceipt.data?.length === 0);
    const invisible = await foreign.client.from('case_activity_reads').insert({
      id: foreignReceiptId, activity_id: activityId, user_id: foreign.user_id,
    });
    record('invisible_activity_receipt_denied', invisible.error?.code === '42501');
    await foreign.client.from('case_activity_reads').update({ created_at: '2000-01-01T00:00:00Z' }).eq('id', receiptId);
    record('foreign_receipt_update_preserved', preserved(await selectOwn()));
    await foreign.client.from('case_activity_reads').delete().eq('id', receiptId);
    record('foreign_receipt_delete_preserved', preserved(await selectOwn()));
    const reassigned = await fixture.client.from('case_activity_reads').update({ user_id: foreign.user_id }).eq('id', receiptId);
    record('read_receipt_user_reassignment_denied', reassigned.error?.code === '42501' && preserved(await selectOwn()));
    requireResult(await fixture.client.from('case_activity_reads').delete().eq('id', receiptId), 'FIXTURE_RECEIPT_DELETE_FAILED');
    const gone = await fixture.client.from('case_activity_reads').select('id').eq('id', receiptId);
    record('owned_receipt_real_delete', !gone.error && gone.data?.length === 0);
  } catch (error) {
    checks.push({ check: 'activity_read_privacy_flow', passed: false,
      code: error instanceof FixtureFailure ? error.safeCode : 'FIXTURE_ACTIVITY_READ_PRIVACY_FAILED' });
  } finally {
    try {
      // IDs exist before requests, so even a committed response that was lost
      // has an exact cleanup target. Activity deletion cascades only its own
      // disposable receipts, including an unexpectedly accepted foreign one.
      requireResult(await fixture.client.from('case_activity').delete()
        .eq('id', activityId).eq('case_id', caseId).eq('user_id', fixture.user_id), 'FIXTURE_ACTIVITY_CLEANUP_FAILED');
      const activity = await fixture.client.from('case_activity').select('id').eq('id', activityId);
      const receipts = await fixture.client.from('case_activity_reads').select('id').eq('activity_id', activityId);
      checks.push({ check: 'activity_read_fixture_cleanup', passed: !activity.error && activity.data?.length === 0
        && !receipts.error && receipts.data?.length === 0 });
    } catch (error) {
      checks.push({ check: 'activity_read_fixture_cleanup', passed: false,
        code: error instanceof FixtureFailure ? error.safeCode : 'FIXTURE_ACTIVITY_CLEANUP_FAILED' });
    }
  }
  return checks;
}
